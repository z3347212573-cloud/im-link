import { spawn } from 'node:child_process';
import path from 'node:path';
import fs from 'node:fs/promises';
const base = await fs.mkdtemp(path.resolve('.test-data/smoke-'));
const env = { ...process.env, IM_LINK_HOME: path.join(base, 'data'), IM_LINK_SOURCE_HOME: path.join(base, 'source'), IM_LINK_SMOKE: '1' };
env.CLAUDE_CONFIG_DIR = path.join(env.IM_LINK_SOURCE_HOME, '.claude');
env.DSH_HOME = path.join(env.IM_LINK_SOURCE_HOME, '.dsh');
delete env.ELECTRON_RUN_AS_NODE;
await fs.mkdir(env.IM_LINK_SOURCE_HOME, { recursive: true });
await fs.mkdir(path.join(env.IM_LINK_SOURCE_HOME, '.claude'), { recursive: true });
await fs.writeFile(path.join(env.IM_LINK_SOURCE_HOME, '.claude', 'settings.json'), '{"fixtureField":"preserve"}');
const dsh = path.join(env.IM_LINK_SOURCE_HOME, '.dsh/profiles/fixture');
await fs.mkdir(dsh, { recursive: true });
await fs.writeFile(path.join(dsh, 'package.json'), '{}');
await fs.writeFile(path.join(dsh, 'cordis.patch.yml'), '# Fixture only\n[]\n');
const executable = process.argv[2] || path.resolve('node_modules/electron/dist/electron.exe');
const child = spawn(executable, process.argv.includes('--packaged') ? [] : [process.cwd()], { env, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
child.stdout.pipe(process.stdout); child.stderr.pipe(process.stderr);
const timeout = setTimeout(() => { console.error('Desktop smoke timeout'); child.kill(); }, 60000);
child.on('error', (error) => { console.error(error.message); process.exitCode = 1; clearTimeout(timeout); });
child.on('exit', (code) => { clearTimeout(timeout); console.log('Desktop exit code:', code); process.exitCode = code ?? 1; });
